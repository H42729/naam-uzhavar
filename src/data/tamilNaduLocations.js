/**
 * Returns array of all district names sorted alphabetically
 */
export function getDistricts() {
  return Object.keys(TAMIL_NADU_DISTRICTS_DATA).sort();
}

/**
 * Returns array of taluks for a given district name
 */
export function getTaluksByDistrict(district) {
  if (!district || !TAMIL_NADU_DISTRICTS_DATA[district]) {
    return [];
  }
  return [...TAMIL_NADU_DISTRICTS_DATA[district]].sort();
}
